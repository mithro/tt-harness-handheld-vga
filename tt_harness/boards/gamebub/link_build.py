_VIVADO_TIMING_TCL = """\
# Generated by tt_harness.boards.gamebub.link_build. Assumptions are in that module's docstring.
create_clock -name sys -period {sys_period:.3f} [get_ports clk50]
create_clock -name spi -period {spi_period:.3f} [get_ports mcu_qspi_clk]
# The same pin at the read clock: the slave only drives dq while the MCU reads, and the MCU
# never reads faster than 16 MHz. The two are alternatives, never at once.
create_clock -name spi_rd -period {rd_period:.3f} -add [get_ports mcu_qspi_clk]
set_clock_groups -physically_exclusive -group [get_clocks spi] -group [get_clocks spi_rd]

# Inputs: mode 0, the MCU launches on the falling edge, the slave captures on the rising edge.
# Timed at 40 MHz (writes); chip select also against spi_rd so that its path to the dq outputs,
# which are timed against spi_rd, exists (clock groups would remove a spi -> spi_rd path).
set spi_in [get_ports {{mcu_qspi_cs_n mcu_qspi_dq[*]}}]
set_input_delay -clock spi -clock_fall -max {in_max} $spi_in
set_input_delay -clock spi -clock_fall -min {in_min} $spi_in
set cs [get_ports mcu_qspi_cs_n]
set_input_delay -clock spi_rd -clock_fall -max {in_max} -add_delay $cs
set_input_delay -clock spi_rd -clock_fall -min {in_min} -add_delay $cs
# Outputs: launched on the falling edge (spi_n), sampled by the MCU on the next rising edge,
# timed at the read clock (and not at 40 MHz: see the results document).
set spi_out [get_ports {{mcu_qspi_dq[*]}}]
set_output_delay -clock spi_rd -max {out_max} $spi_out
set_output_delay -clock spi_rd -min {out_min} $spi_out
# Chip select rising releases the bus combinationally (dq_oe is gated by cs_n): that path,
# cs_n to dq, is timed as cs_n launched like any MCU output against the read clock's edge.

# Buttons are asynchronous inputs into a synchroniser; mcu_irq, the PMOD and the test points
# are slow observation outputs (or a level interrupt) with no timing relation to any clock.
set_false_path -from [get_ports {{buttons_*}}]
set_false_path -to [get_ports {{mcu_irq pmod[*] tp[*]}}]

# First stage of every synchroniser (an ASYNC_REG flip-flop whose D pin is not driven by a
# flip-flop of its own clock): the crossing is the synchroniser's job, so no data path timing.
proc ff_clock {{cell}} {{
    return [get_clocks -quiet -of_objects [get_pins $cell/C]]
}}
set first_stage {{}}
set all_async [get_cells -hier -filter {{IS_SEQUENTIAL && ASYNC_REG}}]
foreach c $all_async {{
    set d [get_pins $c/D]
    set drivers [get_pins -quiet -of_objects [get_nets -of_objects $d] \\
        -filter {{IS_LEAF && DIRECTION == OUT}}]
    set same 0
    foreach p $drivers {{
        set dc [get_cells -of_objects $p]
        if {{[get_property IS_SEQUENTIAL $dc] && [ff_clock $dc] == [ff_clock $c]}} {{ set same 1 }}
    }}
    if {{!$same}} {{ lappend first_stage $d }}
}}
puts "tt-harness synchroniser flops: [llength $all_async], first stages: [llength $first_stage]"
if {{[llength $first_stage] == 0}} {{ error "tt-harness: no synchroniser first stage found" }}
foreach p $first_stage {{ puts "tt-harness first stage: $p" }}
set_false_path -to $first_stage

# Direct multi-bit crossings, spi registers sampled by sys: data path delay only.
set fwd [get_cells -hier -filter {{IS_SEQUENTIAL && NAME =~ *fwd_word*_reg*}}]
set clr [get_cells -hier -filter {{IS_SEQUENTIAL && NAME =~ *clr_mask*_reg*}}]
puts "tt-harness multi-bit crossing flops: fwd_words [llength $fwd], clr_mask [llength $clr]"
if {{[llength $fwd] == 0 || [llength $clr] == 0}} {{ error "tt-harness: crossing flops not found" }}
set_max_delay -datapath_only -from [concat $fwd $clr] -to [get_clocks sys] {crossing}
"""

