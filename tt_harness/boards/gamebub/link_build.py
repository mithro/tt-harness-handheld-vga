_NEXTPNR_PREPACK = """\
# Generated by tt_harness.boards.gamebub.link_build: constrain the two global clocks. The BUFG
# outputs are found by their cell names. nextpnr-xilinx 0.8.2 times a cell on a clock's falling
# edge as on its rising edge, so a clock with users on both edges is constrained at twice its
# frequency (every path, the half-cycle ones included, is then checked against half a period).
CLOCK_PORTS = {{
    "C": "IS_C_INVERTED", "CLK": "IS_CLK_INVERTED", "WCLK": "IS_WCLK_INVERTED",
    "CLKARDCLK": "IS_CLKARDCLK_INVERTED", "CLKBWRCLK": "IS_CLKBWRCLK_INVERTED",
}}


def param_set(cell, key):
    for k, v in cell.params:
        if k == key:
            return "1" in str(v)
    return False


users = {{}}  # net -> [cells, rising, falling]
for name, cell in ctx.cells:
    for port, info in cell.ports:
        if port in CLOCK_PORTS and info.net is not None:
            u = users.setdefault(info.net.name, [0, 0, 0])
            u[0] += 1
            falling = cell.type.endswith("_1") or param_set(cell, CLOCK_PORTS[port])
            u[2 if falling else 1] += 1
for name, cell in ctx.cells:
    if cell.type != "BUFG" or cell.ports["O"].net is None:
        continue
    domain = {{"{sys_bufg}": ("sys", {sys_mhz}), "{spi_bufg}": ("spi", {spi_mhz})}}.get(name)
    if domain is None:
        raise RuntimeError("tt-harness: unexpected BUFG " + name)
    net = cell.ports["O"].net
    cells, rise, fall = users.get(net.name, [0, 0, 0])
    both = rise > 0 and fall > 0
    mhz = domain[1] * 2 if both else domain[1]
    ctx.addClock(net.name, mhz)
    print(
        f"tt-harness clock: domain {{domain[0]}} net '{{net.name}}' {{mhz}} MHz "
        f"(cells {{cells}} rising {{rise}} falling {{fall}}{{' half-cycle' if both else ''}})"
    )
# Every cell on a clock pin not driven by one of the two BUFGs is a clock off the global network.
buf_nets = {{c.ports["O"].net.name for n, c in ctx.cells if c.type == "BUFG"}}
for name, cell in ctx.cells:
    for port, info in cell.ports:
        if port in CLOCK_PORTS and info.net is not None and info.net.name not in buf_nets:
            print(f"tt-harness off-network clock: {{name}}.{{port}} net '{{info.net.name}}'")
"""


def nextpnr_prepack() -> str:
    return _NEXTPNR_PREPACK.format(
        sys_bufg=link_top.SYS_BUFG, spi_bufg=link_top.SPI_BUFG, sys_mhz=SYS_MHZ, spi_mhz=SPI_MHZ
    )


def _tool(name: str) -> Path:
    path = tools.find(name)
    if path is None:
        raise FileNotFoundError(f"{name} not found; run: uv run scripts/setup_toolchains.py")
    return path


def _step(log: Path, what: str, cmd: list[str], cwd: Path, **kwargs) -> str:
    start = log.stat().st_size
    rc = verilate.run(cmd, log, cwd, STEP_TIMEOUT_S, **kwargs)
    with log.open("rb") as f:
        f.seek(start)
        text = f.read().decode(errors="replace")
    if rc != 0:
        first = re.search(r"^(?:ERROR|Error|error)\b.*$", text, re.MULTILINE)
        raise TimingError(
            f"{what} failed (exit {rc})" + (f": {first.group(0)}" if first else ""), log
        )
    return text


def build_openxc7(out_dir: Path, seed: int = 1) -> LinkBuildResult:
    """yosys, nextpnr-xilinx, fasm2frames and xc7frames2bit; the logs go in out_dir.

    Raises ``TimingError`` when nextpnr-xilinx's own timing check fails (it exits non-zero
    after writing nothing, so there is no bitstream) or a clock is left unconstrained.
    """
    out_dir = Path(out_dir).resolve()
    top_v, pins, log = _prepare(out_dir)
    top = link_top.NAME
    for stale in (f"{top}.json", f"{top}.fasm", f"{top}.frames", f"{top}.bit"):
        (out_dir / stale).unlink(missing_ok=True)
    script = out_dir / "synth.ys"
    script.write_text(
        "\n".join(
            [
                f"read_verilog {top_v}",
                # The BUFGs are explicit, as in the compare build.
                f"synth_xilinx -flatten -abc9 -noclkbuf -arch xc7 -top {top}",
                "delete t:$scopeinfo t:$print t:$check",
                f"tee -o {out_dir / 'utilization-yosys.txt'} stat",
                f"write_json {out_dir / (top + '.json')}",
            ]
        )
        + "\n"
    )
    _step(log, "synthesis (yosys)", [str(_tool("yosys")), "-s", str(script)], out_dir)
    prepack = out_dir / "clocks.py"
    prepack.write_text(nextpnr_prepack())
    chipdb = CHIPDB / f"{DEVICE}.bin"
    if not chipdb.is_file():
        raise FileNotFoundError(f"no nextpnr-xilinx chip database {chipdb}")
    fasm = out_dir / f"{top}.fasm"
    cmd = [
        str(_tool("nextpnr-xilinx")),
        "--chipdb",
        str(chipdb),
        "--xdc",
        str(pins),
        "--json",
        str(out_dir / f"{top}.json"),
        "--pre-pack",
        str(prepack),
        "--seed",
        str(seed),
        "--fasm",
        str(fasm),
    ]
    text = _step(log, "place and route (nextpnr-xilinx)", cmd, out_dir)
    (out_dir / "nextpnr.log").write_text(text)
    db = PRJXRAY_DB / "artix7"
    frames = out_dir / f"{top}.frames"
    _step(
        log,
        "fasm2frames",
        [str(_tool("fasm2frames")), "--part", DEVICE, "--db-root", str(db), str(fasm)],
        out_dir,
        stdout=frames,
    )
    bit = out_dir / f"{top}.bit"
    _step(
        log,
        "xc7frames2bit",
        [
            str(_tool("xc7frames2bit")),
            "--part_file",
            str(db / DEVICE / "part.yaml"),
            "--part_name",
            DEVICE,
            "--frm_file",
            str(frames),
            "--output_file",
            str(bit),
        ],
        out_dir,
    )
    result = LinkBuildResult("openxc7", out_dir, bit, log=log)
    parse_nextpnr_link(result, text)
    return result


_PREPACK_CLOCK = re.compile(
    r"^tt-harness clock: domain (?P<domain>\S+) net '(?P<net>.*)' (?P<mhz>[\d.]+) MHz "
    r"\(cells (?P<cells>\d+) rising (?P<rising>\d+) falling (?P<falling>\d+)(?P<half> half-cycle)?\)",
    re.MULTILINE,
)


def parse_nextpnr_link(result: LinkBuildResult, text: str) -> None:
    """Fill ``result.clocks`` from nextpnr-xilinx's final report; raise on a gate failure.

    nextpnr-xilinx has no hold analysis, so the hold slack is None. A clock with users on
    both edges is constrained at twice its frequency and reported as its real frequency.
    """
    log = result.log
    clocks = {m["domain"]: m for m in _PREPACK_CLOCK.finditer(text)}
    if set(clocks) != {"sys", "spi"}:
        raise TimingError(
            f"unconstrained: clocks constrained by the pre-pack are {set(clocks)}", log
        )
    off = re.findall(r"^tt-harness off-network clock: .*$", text, re.MULTILINE)
    if off:
        raise TimingError(f"clock(s) off the global network: {off}", log)
    fmax = {}
    for m in NEXTPNR_FMAX.finditer(text):
        fmax[m["name"]] = (float(m["achieved"]), m["verdict"], float(m["target"]))  # last wins
    for domain, m in clocks.items():
        net = m["net"]
        entries = [v for k, v in fmax.items() if k == net or k.endswith(net)]
        if len(entries) != 1:
            raise TimingError(f"nextpnr-xilinx reported no timing for clock {domain} ({net})", log)
        achieved, verdict, target = entries[0]
        if abs(target - float(m["mhz"])) > 0.01:
            raise TimingError(f"clock {domain} timed against {target} MHz, not {m['mhz']}", log)
        factor = 2.0 if m["half"] else 1.0
        real = float(m["mhz"]) / factor
        # Slack from the period: positive when the achieved frequency exceeds the target.
        slack = 1000.0 / target - 1000.0 / achieved
        result.clocks[domain] = (real, slack, None)
        if verdict != "PASS":
            raise TimingError(
                f"nextpnr-xilinx: clock {domain} fails: {achieved} MHz against {target} MHz", log
            )


def clean(out_dir: Path) -> None:
    shutil.rmtree(out_dir, ignore_errors=True)
