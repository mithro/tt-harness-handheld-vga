def vivado_timing_tcl() -> str:
    return _VIVADO_TIMING_TCL.format(
        sys_period=1000.0 / SYS_MHZ,
        spi_period=1000.0 / SPI_MHZ,
        rd_period=1000.0 / SPI_READ_MHZ,
        in_max=INPUT_DELAY_MAX_NS,
        in_min=INPUT_DELAY_MIN_NS,
        out_max=OUTPUT_DELAY_MAX_NS,
        out_min=OUTPUT_DELAY_MIN_NS,
        crossing=CROSSING_MAX_DELAY_NS,
    )


def _prepare(out_dir: Path) -> tuple[Path, Path, Path]:
    """Write the top Verilog, the pin constraints and an empty log; return their paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    platform = Platform("vivado")
    top_v, _ = link_top.top_verilog(platform, out_dir / f"{link_top.NAME}.v")
    pins = out_dir / "pins.xdc"
    pins.write_text(link_top.pin_xdc(platform))
    log = out_dir / LOG_NAME
    log.write_text("")
    return top_v, pins, log


def build_vivado(out_dir: Path, jobs: int = MAX_JOBS) -> LinkBuildResult:
    """Synthesise, place, route and write a bitstream with Vivado; reports go in out_dir."""
    settings = tools.vivado_settings()
    if settings is None:
        raise FileNotFoundError(f"Vivado not found at {tools.VIVADO_SETTINGS}")
    out_dir = Path(out_dir).resolve()
    top_v, pins, log = _prepare(out_dir)
    for stale in out_dir.glob("*.rpt"):
        stale.unlink()
    (out_dir / f"{link_top.NAME}.bit").unlink(missing_ok=True)
    timing = out_dir / "timing.tcl"
    timing.write_text(vivado_timing_tcl())
    script = out_dir / "build.tcl"
    script.write_text(
        _VIVADO_BUILD_TCL.format(
            jobs=min(jobs, MAX_JOBS),
            top_v=top_v,
            pins=pins,
            top=link_top.NAME,
            part=DEVICE,
            timing=timing,
            out=out_dir,
        )
    )
    shell = (
        f'source "{settings}" && exec vivado -mode batch -nojournal '
        f'-log "{out_dir / "vivado.log"}" -source "{script}"'
    )
    rc = verilate.run(["bash", "-c", shell], log, out_dir, STEP_TIMEOUT_S)
    if rc != 0:
        raise TimingError(f"Vivado failed (exit {rc}); see {log} and {out_dir / 'vivado.log'}", log)
    result = LinkBuildResult("vivado", out_dir, out_dir / f"{link_top.NAME}.bit", log=log)
    try:
        parse_vivado_link(result)
    except TimingError:
        # A build that fails the gate leaves no bitstream behind.
        (out_dir / f"{link_top.NAME}.bit").unlink(missing_ok=True)
        raise
    return result


_CHECK = re.compile(r"^\d+\. checking (\w+) \((\d+)\)\s*$", re.MULTILINE)
# Every check_timing item. The first group leaves part of the design untimed: all must be zero.
VIVADO_CHECKS_ZERO = (
    "no_clock",
    "constant_clock",
    "pulse_width_clock",
    "unconstrained_internal_endpoints",
    "multiple_clock",
    "generated_clocks",
    "loops",
    "partial_input_delay",
    "partial_output_delay",
    "latch_loops",
)
# Ports without an input or output delay: justified in the results document.
VIVADO_CHECKS_PORTS = ("no_input_delay", "no_output_delay")


def vivado_check_counts(text: str) -> dict[str, int]:
    return {m.group(1): int(m.group(2)) for m in _CHECK.finditer(text)}


def parse_vivado_link(result: LinkBuildResult) -> None:
    """Fill ``result.clocks`` from the timing summary; raise ``TimingError`` on a gate failure."""
    out = result.out_dir
    log = result.log
    if not result.bitstream.is_file():
        raise TimingError("Vivado wrote no bitstream", log)
    text = (out / "timing.rpt").read_text()
    checks = vivado_check_counts((out / "check_timing.rpt").read_text() + "\n" + text)
    missing = [c for c in VIVADO_CHECKS_ZERO + VIVADO_CHECKS_PORTS if c not in checks]
    if missing:
        raise TimingError(f"Vivado check_timing report lacks {missing}", log)
    bad = {c: checks[c] for c in VIVADO_CHECKS_ZERO if checks[c]}
    if bad:
        raise TimingError(f"unconstrained: Vivado check_timing reports {bad}", log)
    periods = {}
    for row in table_rows(text, "Clock Summary"):
        periods[row[0]] = float(row[-2])
    if set(periods) != {"sys", "spi", "spi_rd"}:
        raise TimingError(f"unconstrained: clocks in the design are {sorted(periods)}", log)
    expected = {"sys": SYS_MHZ, "spi": SPI_MHZ, "spi_rd": SPI_READ_MHZ}
    if any(abs(periods[n] - 1000 / mhz) > 0.001 for n, mhz in expected.items()):
        raise TimingError(f"clock periods are {periods}, not the constraints", log)
    for row in table_rows(text, "Intra Clock Table"):
        name = row[0]
        if len(row) != 13:
            raise TimingError(f"clock {name} has no setup or hold figures: {row}", log)
        wns, whs, wpws = ns_value(row[1]), ns_value(row[5]), ns_value(row[9])
        result.clocks[name] = (1000.0 / periods[name], wns, whs)
        if wns < 0 or whs < 0 or wpws < 0:
            raise TimingError(
                f"Vivado: clock {name} misses timing (WNS {wns}, WHS {whs}, WPWS {wpws})", log
            )
    if set(result.clocks) != set(expected):
        raise TimingError(f"clock(s) absent from the intra-clock table: {result.clocks}", log)
    for row in table_rows(text, "Inter Clock Table"):
        # A pair held only by set_max_delay -datapath_only has no hold figures.
        wns = ns_value(row[2])
        whs = ns_value(row[6]) if len(row) > 6 else None
        if wns is not None and (wns < 0 or (whs is not None and whs < 0)):
            raise TimingError(f"Vivado: inter-clock {row[0]} -> {row[1]} misses timing", log)
    if "All user specified timing constraints are met." not in text:
        raise TimingError("Vivado does not report all user timing constraints met", log)


