"""Build ``link_top`` (``QspiSlave`` + ``McuLink`` on the Game Bub pins) with Vivado or openXC7.

``tt_harness.build`` is built around the compare build (its clock plan, its ``pclk``
register, its generated top), so only its lower-level pieces are used here: the tool runner
(``verilate.run``), tool lookup (``tools``), chip database and X-Ray database locations, the
nextpnr-xilinx clock-line pattern, ``TimingError`` and the Vivado summary table reader. The
flows, constraints and the gate are this module's.

Constraints (the numbers, and what each assumes; ``docs/results/2026-11-spike-c-gamebub-link-
synthesis.md`` explains them):

- ``sys``: 50 MHz on the oscillator pin.
- ``spi``: 40 MHz (25 ns) on the MCU's SPI clock pin, the firmware's write clock; all inputs
  and every path inside the design are timed at it. ``spi_rd``: the same pin at 16 MHz (the
  firmware's cap on reads, which run at 10 MHz), declared with ``create_clock -add`` and
  physically exclusive with ``spi``; the ``dq`` outputs are timed against it only, because the
  slave drives ``dq`` only during a read.
- Inputs (``cs_n``, ``dq``): SPI mode 0, the MCU changes them after the falling edge and the
  slave samples on the rising edge, so each has half a period (12.5 ns). Vivado:
  ``set_input_delay -clock spi -clock_fall`` with ``INPUT_DELAY_MAX_NS`` / ``_MIN_NS``. These
  two numbers are ASSUMPTIONS about the ESP32-S3's output timing and the board's flight time;
  the datasheet figures are not in this repository.
- Outputs (``dq``): launched from the falling edge, sampled by the MCU on the next rising
  edge: ``set_output_delay -clock spi_rd`` with ``OUTPUT_DELAY_MAX_NS`` (the MCU's setup time plus
  flight, ASSUMED) and ``OUTPUT_DELAY_MIN_NS`` (minus the MCU's hold time, ASSUMED 0).
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from tt_harness import tools, verilate
from tt_harness.build import (
    CHIPDB,
    MAX_JOBS,
    NEXTPNR_FMAX,
    PRJXRAY_DB,
    STEP_TIMEOUT_S,
    TimingError,
    ns_value,
    table_rows,
)

from . import link_top
from .platform import DEVICE, Platform

SYS_MHZ = 50.0
SPI_MHZ = 40.0
SPI_READ_MHZ = 16.0  # the firmware caps its reads at 16 MHz (they run at 10 MHz)
INPUT_DELAY_MAX_NS = 6.0  # ASSUMPTION: MCU output valid at most 6 ns after the falling edge
INPUT_DELAY_MIN_NS = 0.0  # ASSUMPTION: and not before the falling edge
OUTPUT_DELAY_MAX_NS = 3.0  # ASSUMPTION: MCU setup plus flight time before its rising edge
OUTPUT_DELAY_MIN_NS = 0.0  # ASSUMPTION: MCU hold requirement 0
# Direct multi-bit spi -> sys crossings: stable for at least two sys periods (40 ns) before sys
# samples them (docs result file, section 2); 20 ns is half of that.
CROSSING_MAX_DELAY_NS = 20.0

LOG_NAME = "build.log"


@dataclass
class LinkBuildResult:
    toolchain: str
    out_dir: Path
    bitstream: Path | None
    # clock name -> (constraint MHz, worst setup slack ns, worst hold slack ns)
    clocks: dict[str, tuple[float, float | None, float | None]] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    log: Path | None = None


