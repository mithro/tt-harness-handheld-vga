"""The demo build's firmware (`firmware/`) in the SoC's ROM, in place of LiteX's BIOS.

`FirmwareBuilder` is LiteX's `Builder` for a `HarnessSoC` whose ROM holds the firmware:
the simulation (`tt_harness.soc.sim`) and the board builds use it the same way,
`FirmwareBuilder(soc, output_dir=...).build(...)`. It

- adds `firmware/` as a software package and does not build the BIOS;
- writes the firmware's generated headers (`write_headers`: `demo_json.h`, the build's
  `demo.json` byte for byte, `firmware_config.h`, `firmware_limits.h` from
  `tt_harness.soc.limits`, and `py_printable.h`, `str.isprintable()` of this Python) next to LiteX's `csr.h`, after
  LiteX generates its own and before anything is compiled;
- compiles with the repository's RISC-V GCC (`RISCV_GCC`) and no other: a missing one is a
  `FileNotFoundError`, never a fall back to a GCC on PATH;
- after the software is compiled, loads `firmware.bin` into the ROM (an image larger than
  the ROM is an error), so the gateware LiteX then writes boots the firmware.

Why the ROM and not main RAM behind the BIOS: the firmware starts at reset, with no BIOS
memory test or serial-boot wait (seconds of simulated time, and a BIOS that tests main RAM
would overwrite a preloaded image), and the image is one file. The ROM is `core.ROM_SIZE`
bytes; data, bss and the parser's token array live in main RAM.

This overrides two private methods of LiteX's `Builder` (`_generate_includes` and
`_generate_rom_software`) at the LiteX version pinned in `pyproject.toml`.
"""

from __future__ import annotations

import contextlib
import os
from collections.abc import Iterator, Sequence
from pathlib import Path

from litex.soc.integration import soc as litex_soc
from litex.soc.integration.builder import Builder

from tt_harness import tools
from tt_harness.soc import core, limits
from tt_harness.soc.core import shuttle_of

FIRMWARE_DIR = Path(__file__).resolve().parent.parent.parent / "firmware"
# The one RISC-V GCC the firmware is built with (`scripts/setup_toolchains.py` puts it here).
RISCV_GCC = tools.TOOLCHAINS / "riscv-gcc" / "bin"
GCC_TRIPLE = "riscv64-unknown-elf"
PACKAGE = "firmware"
IMAGE = "firmware.bin"


# The firmware builds its fixed-format console lines in a 512-byte buffer: these bound the
# two parts of a line whose length depends on the build.
MAX_NAME = 128  # bytes of the project name (the `boot` line)
MAX_PROBES = 32  # framebuffer probes (the `fb` line)


def _c_string(text: str) -> str:
    if not all(32 <= ord(c) < 127 and c not in '"\\' for c in text):
        raise ValueError(f"not a plain ASCII name: {text!r}")
    return f'"{text}"'


def firmware_config_header(project_name: str, fb_probes: Sequence[int]) -> str:
    """`firmware_config.h`: the project name, its shuttle (for the demo.json check) and the
    framebuffer pixels the firmware reports in `fb` lines (none: no `fb` lines)."""
    if len(project_name) > MAX_NAME:
        raise ValueError(f"project name longer than {MAX_NAME} bytes: {project_name!r}")
    if len(fb_probes) > MAX_PROBES:
        raise ValueError(f"{len(fb_probes)} framebuffer probes, more than {MAX_PROBES}")
    probes = ", ".join(str(int(p)) for p in fb_probes) or "0"
    return (
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by tt_harness/soc/firmware.py (firmware_config_header). */\n"
        "#ifndef TT_HARNESS_FIRMWARE_CONFIG_H\n"
        "#define TT_HARNESS_FIRMWARE_CONFIG_H\n"
        "\n"
        "#include <stdint.h>\n"
        "\n"
        f"#define TT_PROJECT_NAME {_c_string(project_name)}\n"
        f"#define TT_SHUTTLE {_c_string(shuttle_of(project_name))}\n"
        f"#define FB_PROBE_COUNT {len(fb_probes)}\n"
        f"static const uint32_t fb_probes[] = {{{probes}}};\n"
        "\n"
        "#endif /* TT_HARNESS_FIRMWARE_CONFIG_H */\n"
    )


def write_headers(
    generated_dir: Path,
    soc: core.HarnessSoC,
    *,
    fb_probes: Sequence[int] = (),
    demo_json: bytes | None = None,
) -> None:
    """Write the firmware's generated headers into `generated_dir`.

    `demo_json` replaces the build's validated `soc.demo_json` in the image: for tests of
    the firmware's own check at boot only (the build refuses an invalid file first).
    """
    n = soc.core.fb.width * soc.core.fb.height
    for p in fb_probes:
        if not 0 <= p < n:
            raise ValueError(f"framebuffer probe {p} is outside 0..{n - 1}")
    generated_dir = Path(generated_dir)
    generated_dir.mkdir(parents=True, exist_ok=True)
    image = soc.demo_json if demo_json is None else demo_json
    (generated_dir / "demo_json.h").write_text(core.demo_json_header(image))
    (generated_dir / "firmware_config.h").write_text(
        firmware_config_header(soc.project_name, fb_probes)
    )
    write_portable_headers(generated_dir)


def nonprintable_runs() -> list[tuple[int, int]]:
    """The code points for which this Python's `str.isprintable()` is False, as [first, last]
    runs, none crossing U+FFFF/U+10000."""
    runs: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000 + 1):
        np = cp <= 0x10FFFF and not chr(cp).isprintable()
        if np and cp == 0x10000 and start is not None:  # split at the plane boundary
            runs.append((start, 0xFFFF))
            start = cp
        if np and start is None:
            start = cp
        elif not np and start is not None:
            runs.append((start, cp - 1))
            start = None
    return runs


def printable_header() -> str:
    """`py_printable.h`: `str.isprintable()` of every code point, as this Python has it,
    for `firmware/pyrepr.c`'s `py_isprintable` (binary search over the runs)."""
    runs = nonprintable_runs()
    bmp = [r for r in runs if r[1] <= 0xFFFF]
    astral = [r for r in runs if r[0] > 0xFFFF]
    assert len(bmp) + len(astral) == len(runs)

    def rows(table: list[tuple[int, int]], per_line: int) -> list[str]:
        cells = [f"{{0x{a:x}, 0x{b:x}}}," for a, b in table]
        return ["    " + " ".join(cells[i : i + per_line]) for i in range(0, len(cells), per_line)]

    return "\n".join(
        [
            "/* SPDX-License-Identifier: Apache-2.0 */",
            "/* Generated by tt_harness/soc/firmware.py (printable_header) from str.isprintable()",
            f" * of {limits.python_version()}; do not edit. */",
            "#ifndef TT_FIRMWARE_PY_PRINTABLE_H",
            "#define TT_FIRMWARE_PY_PRINTABLE_H",
            "",
            "#include <stdint.h>",
            "",
            f'#define PY_PRINTABLE_SOURCE "{limits.python_version()}"',
            "",
            "/* The code points str.isprintable() is False for: [first, last], ascending. */",
            f"static const uint16_t py_nonprintable_bmp[{len(bmp)}][2] = {{",
            *rows(bmp, 6),
            "};",
            f"static const uint32_t py_nonprintable_astral[{len(astral)}][2] = {{",
            *rows(astral, 4),
            "};",
            "",
            "#endif /* TT_FIRMWARE_PY_PRINTABLE_H */",
            "",
        ]
    )


def write_portable_headers(directory: Path) -> None:
    """The generated headers that do not depend on the SoC (the host tests build with them
    too): `firmware_limits.h` and `py_printable.h`."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "firmware_limits.h").write_text(limits.header())
    (directory / "py_printable.h").write_text(printable_header())


@contextlib.contextmanager
def pinned_gcc() -> Iterator[None]:
    """`RISCV_GCC` first on PATH and LiteX told to use its triple, for the duration."""
    gcc = RISCV_GCC / f"{GCC_TRIPLE}-gcc"
    if not (gcc.is_file() and os.access(gcc, os.X_OK)):
        raise FileNotFoundError(f"no RISC-V GCC at {gcc}: run scripts/setup_toolchains.py")
    old = {k: os.environ.get(k) for k in ("PATH", "LITEX_ENV_CC_TRIPLE")}
    os.environ["PATH"] = f"{RISCV_GCC}{os.pathsep}{old['PATH'] or ''}"
    os.environ["LITEX_ENV_CC_TRIPLE"] = GCC_TRIPLE
    try:
        yield
    finally:
        for k, v in old.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


class FirmwareBuilder(Builder):
    """LiteX's `Builder`, with the firmware in the ROM; see the module docstring."""

    def __init__(
        self,
        soc: core.HarnessSoC,
        *,
        fb_probes: Sequence[int] = (),
        demo_json: bytes | None = None,
        **kwargs,
    ) -> None:
        super().__init__(soc, compile_software=True, **kwargs)
        self.fb_probes = tuple(fb_probes)
        self.boot_demo_json = demo_json
        self.add_software_package(PACKAGE, str(FIRMWARE_DIR))
        soc.integrated_rom_initialized = True  # no BIOS: the ROM is ours

    def build(self, *args, **kwargs):
        with pinned_gcc():
            return super().build(*args, **kwargs)

    @property
    def firmware_dir(self) -> Path:
        return Path(self.software_dir) / PACKAGE

    @property
    def image(self) -> Path:
        return self.firmware_dir / IMAGE

    def _generate_includes(self, with_bios=True):
        super()._generate_includes(with_bios=with_bios)
        write_headers(
            Path(self.generated_dir),
            self.soc,
            fb_probes=self.fb_probes,
            demo_json=self.boot_demo_json,
        )

    def _generate_rom_software(self, compile_bios=True):
        super()._generate_rom_software(compile_bios=False)
        image = self.image
        rom = self.soc.bus.regions["rom"].size
        size = image.stat().st_size
        if size > rom:
            raise ValueError(f"the firmware is {size} bytes, more than the {rom}-byte ROM")
        data = litex_soc.get_mem_data(
            str(image),
            data_width=self.soc.bus.data_width,
            endianness=self.soc.cpu.endianness,
        )
        words = rom // (self.soc.bus.data_width // 8)
        self.soc.init_rom(name="rom", contents=data + [0] * (words - len(data)), auto_size=False)
