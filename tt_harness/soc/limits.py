"""The firmware's limits, defined once: what `firmware/demo_parse.c` can hold of a
`demo.json`, its "firmware limit: ..." messages, and the same check in Python.

The firmware has no dynamic memory, so a file the board's validator accepts can still be more
than it holds. `header()` is the C form (`firmware_limits.h`, written into the build by
`tt_harness.soc.firmware.write_headers`, and by the host tests): the numbers and the fixed
messages. `check(text, shuttle)` gives, for a file `tt_harness.demo.validate` accepts, the
messages the firmware gives at boot, in its order, so the build refuses the file with the
same text first (`tt_harness.soc.core.demo_entry`).

`stored(messages)` is how the firmware keeps messages in its `DEMO_ERRORS_TEXT` bytes: a
message that does not fit is left out and counted, later ones that fit are kept, and a last
message says how many were left out.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from typing import Any

PREFIX = "firmware limit: "

MAX_TOKENS = 2048  # JSON tokens (jsmn's), 16 bytes each
MAX_PROJECTS = 32  # entries of "projects"
MAX_STEPS = 512  # steps of all projects together
MAX_DEPTH = 32  # nesting of arrays and objects (the top value is depth 0)
ERRORS_TEXT = 4096  # bytes for all messages together
SHUTTLE_MAX = 64  # bytes of the shuttle name with its NUL
MAX_DIGITS = 100  # significant digits of a number literal
MAX_MS = 2**31 - 1  # duration_ms and wait_ms: the runner's clock is 32 bits, compared signed
MAX_U32 = 2**32 - 1  # address, subtile, clock_hz

TOKENS = f"{PREFIX}more than {MAX_TOKENS} JSON tokens (DEMO_MAX_TOKENS)"
DEPTH = f"{PREFIX}JSON nested deeper than {MAX_DEPTH} (DEMO_MAX_DEPTH)"
DIGITS = f"{PREFIX}a number with more than {MAX_DIGITS} significant digits (PY_MAX_DIGITS)"
SHUTTLE = f"{PREFIX}a shuttle name longer than {SHUTTLE_MAX - 1} bytes (DEMO_SHUTTLE_MAX)"
PROJECTS = f"{PREFIX}more than {MAX_PROJECTS} projects (DEMO_MAX_PROJECTS)"
STEPS = f"{PREFIX}more than {MAX_STEPS} steps in all projects (DEMO_MAX_STEPS)"
NOT_SHOWN = f"{PREFIX}messages not shown, more than fit in DEMO_ERRORS_TEXT ({ERRORS_TEXT} bytes): "

# Each kept message takes its length (2 bytes), its bytes and a NUL; room for the last
# message, with the largest count, is always kept free.
NOT_SHOWN_ROOM = 2 + len(NOT_SHOWN) + len(str(2**32 - 1)) + 1

# The fields the firmware reads as 32-bit values, in its order, and their largest value.
ENTRY_FIELDS = (
    ("address", MAX_U32),
    ("subtile", MAX_U32),
    ("duration_ms", MAX_MS),
    ("clock_hz", MAX_U32),
    ("ui_in", 255),
)


def value(where: str, field: str, v: int, limit: int) -> str:
    return f'{PREFIX}{where}: "{field}" is {v}, more than {limit}'


def _c_string(text: str) -> str:
    assert all(32 <= ord(c) < 127 and c not in '"\\' for c in text), text
    return f'"{text}"'


def header() -> str:
    """`firmware_limits.h`."""
    numbers = [
        ("DEMO_MAX_TOKENS", MAX_TOKENS),
        ("DEMO_MAX_PROJECTS", MAX_PROJECTS),
        ("DEMO_MAX_STEPS", MAX_STEPS),
        ("DEMO_MAX_DEPTH", MAX_DEPTH),
        ("DEMO_ERRORS_TEXT", ERRORS_TEXT),
        ("DEMO_SHUTTLE_MAX", SHUTTLE_MAX),
        ("PY_MAX_DIGITS", MAX_DIGITS),
        ("DEMO_NOT_SHOWN_ROOM", NOT_SHOWN_ROOM),
    ]
    unsigned = [("DEMO_MAX_MS", MAX_MS), ("DEMO_MAX_U32", MAX_U32)]
    strings = [
        ("DEMO_LIMIT_PREFIX", PREFIX),
        ("DEMO_MSG_TOKENS", TOKENS),
        ("DEMO_MSG_DEPTH", DEPTH),
        ("DEMO_MSG_DIGITS", DIGITS),
        ("DEMO_MSG_SHUTTLE", SHUTTLE),
        ("DEMO_MSG_PROJECTS", PROJECTS),
        ("DEMO_MSG_STEPS", STEPS),
        ("DEMO_MSG_NOT_SHOWN", NOT_SHOWN),
    ]
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tt_harness/soc/limits.py (header); do not edit. */",
        "#ifndef TT_FIRMWARE_LIMITS_H",
        "#define TT_FIRMWARE_LIMITS_H",
        "",
        *(f"#define {n} {v}" for n, v in numbers),
        *(f"#define {n} {v}u" for n, v in unsigned),
        *(f"#define {n} {_c_string(v)}" for n, v in strings),
        "",
        "#endif /* TT_FIRMWARE_LIMITS_H */",
        "",
    ]
    return "\n".join(lines)


# ---- the check -----------------------------------------------------------------------------


def _significant_digits(literal: str) -> int:
    """`py_significant_digits`: the digits before any exponent, from the first non-zero one
    to the last non-zero one."""
    mantissa = literal.lstrip("-").split("e")[0].split("E")[0].replace(".", "")
    stripped = mantissa.strip("0")
    return len(stripped)


def _json_limit(text: str) -> str | None:
    """The firmware's first limit on the JSON itself: tokens, then depth, then digits."""
    longest = [0]

    def number(literal: str, convert: Any) -> Any:
        longest[0] = max(longest[0], _significant_digits(literal))
        return convert(literal)

    tree = json.loads(
        text,
        parse_int=lambda s: number(s, int),
        parse_float=lambda s: number(s, float),
        object_pairs_hook=lambda pairs: ("object", pairs),
    )

    def walk(v: Any, depth: int) -> tuple[int, int]:  # (tokens, deepest)
        if isinstance(v, tuple) and len(v) == 2 and v[0] == "object":
            tokens, deepest = 1, depth
            for _key, item in v[1]:
                t, d = walk(item, depth + 1)
                tokens, deepest = tokens + 1 + t, max(deepest, d)  # the key is a token
            return tokens, deepest
        if isinstance(v, list):
            tokens, deepest = 1, depth
            for item in v:
                t, d = walk(item, depth + 1)
                tokens, deepest = tokens + t, max(deepest, d)
            return tokens, deepest
        return 1, depth

    sys.setrecursionlimit(max(sys.getrecursionlimit(), 10_000))
    tokens, deepest = walk(tree, 0)
    if tokens > MAX_TOKENS:
        return TOKENS
    if deepest > MAX_DEPTH:
        return DEPTH
    if longest[0] > MAX_DIGITS:
        return DIGITS
    return None


def check(text: str, shuttle: str) -> list[str]:
    """The firmware's messages for `text`, a file `validate.parse(text, shuttle)` accepts;
    [] if the firmware holds it. As `stored` keeps them."""
    first = _json_limit(text)
    if first is not None:
        return [first]
    demo = json.loads(text)
    out: list[str] = []
    if len(shuttle.encode()) > SHUTTLE_MAX - 1:
        return [SHUTTLE]
    projects = demo["projects"]
    if len(projects) > MAX_PROJECTS:
        return [PROJECTS]
    steps_seen = 0
    for i, entry in enumerate(projects):
        for field, limit in ENTRY_FIELDS:
            if entry[field] > limit:
                out.append(value(f"project {i}", field, entry[field], limit))
        steps = entry["steps"]
        if steps_seen + len(steps) > MAX_STEPS:
            out.append(STEPS)
            return stored(out)
        steps_seen += len(steps)
        for n, step in enumerate(steps):
            if "wait_ms" in step and step["wait_ms"] > MAX_MS:
                out.append(value(f"project {i} step {n}", "wait_ms", step["wait_ms"], MAX_MS))
    return stored(out)


def stored(messages: list[str]) -> list[str]:
    """The messages as the firmware keeps them in `DEMO_ERRORS_TEXT` bytes (module
    docstring)."""
    kept: list[str] = []
    used = 0
    left_out = 0
    for m in messages:
        size = 2 + len(m.encode("utf-8", errors="surrogatepass")) + 1
        if used + size + NOT_SHOWN_ROOM <= ERRORS_TEXT:
            kept.append(m)
            used += size
        else:
            left_out += 1
    if left_out:
        kept.append(f"{NOT_SHOWN}{left_out}")
    return kept


def python_version() -> str:
    """The Python and Unicode versions of this check (and of the generated tables)."""
    return f"Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}"
